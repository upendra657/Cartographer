-- 0. Force Master System Privileges
USE ROLE ACCOUNTADMIN;

-- 1. Create the Database and Schemas
CREATE DATABASE IF NOT EXISTS CARTOGRAPHER_DB;
CREATE SCHEMA IF NOT EXISTS CARTOGRAPHER_DB.RAW;        
CREATE SCHEMA IF NOT EXISTS CARTOGRAPHER_DB.STAGING;    
CREATE SCHEMA IF NOT EXISTS CARTOGRAPHER_DB.MARTS;      

-- 2. Create Enterprise Roles
CREATE ROLE IF NOT EXISTS LOADER;       
CREATE ROLE IF NOT EXISTS TRANSFORMER;  
CREATE ROLE IF NOT EXISTS REPORTER;     

-- 3. Grant Privileges
GRANT USAGE ON DATABASE CARTOGRAPHER_DB TO ROLE LOADER;
GRANT USAGE ON DATABASE CARTOGRAPHER_DB TO ROLE TRANSFORMER;
GRANT USAGE ON DATABASE CARTOGRAPHER_DB TO ROLE REPORTER;

GRANT ALL PRIVILEGES ON SCHEMA CARTOGRAPHER_DB.RAW TO ROLE LOADER;

GRANT USAGE ON SCHEMA CARTOGRAPHER_DB.RAW TO ROLE TRANSFORMER;
GRANT SELECT ON ALL TABLES IN SCHEMA CARTOGRAPHER_DB.RAW TO ROLE TRANSFORMER;
GRANT ALL PRIVILEGES ON SCHEMA CARTOGRAPHER_DB.STAGING TO ROLE TRANSFORMER;
GRANT ALL PRIVILEGES ON SCHEMA CARTOGRAPHER_DB.MARTS TO ROLE TRANSFORMER;

GRANT USAGE ON SCHEMA CARTOGRAPHER_DB.MARTS TO ROLE REPORTER;
GRANT SELECT ON ALL TABLES IN SCHEMA CARTOGRAPHER_DB.MARTS TO ROLE REPORTER;

-- 4. Grant Roles to Your User
GRANT ROLE LOADER TO USER UPENDRA657;
GRANT ROLE TRANSFORMER TO USER UPENDRA657;
GRANT ROLE REPORTER TO USER UPENDRA657;
